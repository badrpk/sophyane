@dataclass(frozen=True)
class CurriculumFamily:
    name: str
    capabilities: tuple[str, ...]
    product_kind: str
    request_patterns: tuple[str, ...]
    concepts: tuple[str, ...]
    interfaces: tuple[str, ...] = ()
    validators: tuple[str, ...] = ()
    priority: float = 1.0


@dataclass
class FamilyStats:
    family: str
    successes: int = 0
    failures: int = 0
    recent_failures: int = 0
    chunks_learned: int = 0
    last_attempt: float = 0.0
    last_success: float = 0.0
    memory_evidence: int = 0
    score: float = 0.0


@dataclass
class CurriculumState:
    version: int = 1
    iteration: int = 0
    seed: int = 0
    family_cursor: dict[str, int] = field(default_factory=dict)
    failure_streaks: dict[str, int] = field(default_factory=dict)
    cooldown_until: dict[str, float] = field(default_factory=dict)
    recent_requests: list[str] = field(default_factory=list)
    family_successes: dict[str, int] = field(default_factory=dict)
    family_failures: dict[str, int] = field(default_factory=dict)


