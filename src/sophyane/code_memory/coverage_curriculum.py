def _append_jsonl(
    path: Path,
    record: dict[str, Any],
) -> None:
    path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    with path.open(
        "a",
        encoding="utf-8",
    ) as handle:
        handle.write(
            json.dumps(
                record,
                ensure_ascii=False,
            )
            + "\n"
        )


def _read_jsonl(
    path: Path,
) -> list[dict[str, Any]]:
    if not path.is_file():
        return []

    output = []

    for line in path.read_text(
        encoding="utf-8",
        errors="replace",
    ).splitlines():
        if not line.strip():
            continue

        try:
            value = json.loads(line)
        except json.JSONDecodeError:
            continue

        if isinstance(value, dict):
            output.append(value)

    return output


def load_state() -> CurriculumState:
    CURRICULUM_ROOT.mkdir(
        parents=True,
        exist_ok=True,
    )

    if not STATE_FILE.is_file():
        return CurriculumState(
            seed=int(time.time()),
        )

    try:
        payload = json.loads(
            STATE_FILE.read_text(
                encoding="utf-8",
            )
        )

        allowed = {
            field_name
            for field_name in (
                "version",
                "iteration",
                "seed",
                "family_cursor",
                "failure_streaks",
                "cooldown_until",
                "recent_requests",
                "family_successes",
                "family_failures",
            )
        }

        return CurriculumState(
            **{
                key: value
                for key, value in payload.items()
                if key in allowed
            }
        )

    except Exception:
        return CurriculumState(
            seed=int(time.time()),
        )


def save_state(
    state: CurriculumState,
) -> None:
    CURRICULUM_ROOT.mkdir(
        parents=True,
        exist_ok=True,
    )

    temporary = STATE_FILE.with_suffix(
        ".json.tmp"
    )

    temporary.write_text(
        json.dumps(
            asdict(state),
            ensure_ascii=False,
            indent=2,
            sort_keys=True,
        )
        + "\n",
        encoding="utf-8",
    )

    temporary.replace(
        STATE_FILE
    )


