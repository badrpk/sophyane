def load_run_statistics() -> dict[str, FamilyStats]:
    stats = {
        family.name:
            FamilyStats(
                family=family.name
            )
        for family in FAMILIES
    }

    events = _read_jsonl(
        EVENTS_FILE
    )

    recent_events = events[-100:]

    for event in events:
        request = str(
            event.get("request")
            or ""
        )

        family_name = (
            event.get("curriculum_family")
            or classify_request_family(
                request
            )
        )

        if family_name not in stats:
            continue

        item = stats[family_name]
        success = bool(
            event.get("success")
        )

        if success:
            item.successes += 1
            item.chunks_learned += int(
                event.get("chunks_learned")
                or 0
            )
            item.last_success = max(
                item.last_success,
                float(
                    event.get("finished_at")
                    or event.get("timestamp")
                    or 0.0
                ),
            )
        else:
            item.failures += 1

        item.last_attempt = max(
            item.last_attempt,
            float(
                event.get("finished_at")
                or event.get("timestamp")
                or 0.0
            ),
        )

    for event in recent_events:
        request = str(
            event.get("request")
            or ""
        )

        family_name = (
            event.get("curriculum_family")
            or classify_request_family(
                request
            )
        )

        if (
            family_name in stats
            and not bool(
                event.get("success")
            )
        ):
            stats[
                family_name
            ].recent_failures += 1

    return stats


def _chunk_meta_values(
    meta: dict[str, Any],
) -> set[str]:
    values = set()

    for key in (
        "provides",
        "roles",
        "exports",
        "requires",
    ):
        raw = meta.get(key) or []

        if isinstance(raw, str):
            raw = [raw]

        for value in raw:
            value = str(
                value
            ).strip().lower()

            if value:
                values.add(value)

    domain = str(
        meta.get("domain")
        or ""
    ).strip().lower()

    if domain:
        values.add(domain)

    return values


def memory_capability_counts() -> dict[str, int]:
    from sophyane.code_memory.store import (
        ChunkStore,
    )

    store = ChunkStore()

    counts: dict[str, int] = {}

    for chunk in store.chunks.values():
        meta = dict(
            getattr(
                chunk,
                "meta",
                None,
            )
            or {}
        )

        if meta.get("exclude"):
            continue

        for capability in _chunk_meta_values(
            meta
        ):
            counts[capability] = (
                counts.get(
                    capability,
                    0,
                )
                + 1
            )

    return counts


def family_memory_evidence(
    family: CurriculumFamily,
    capability_counts: dict[str, int],
) -> int:
    return sum(
        min(
            10,
            capability_counts.get(
                capability.lower(),
                0,
            ),
        )
        for capability in family.capabilities
    )


def score_families(
    state: CurriculumState,
    *,
    now: float | None = None,
) -> list[FamilyStats]:
    now = (
        float(now)
        if now is not None
        else time.time()
    )

    stats = load_run_statistics()
    capability_counts = (
        memory_capability_counts()
    )

    for family in FAMILIES:
        item = stats[family.name]

        item.memory_evidence = (
            family_memory_evidence(
                family,
                capability_counts,
            )
        )

        target_gap = max(
            0,
            DEFAULT_TARGET_SUCCESSES
            - item.successes,
        )

        evidence_gap = max(
            0,
            len(family.capabilities) * 4
            - item.memory_evidence,
        )

        failure_rate = (
            item.failures
            / max(
                1,
                item.successes
                + item.failures,
            )
        )

        recency_hours = (
            (
                now - item.last_attempt
            )
            / 3600.0
            if item.last_attempt
            else 999.0
        )

        cooldown = float(
            state.cooldown_until.get(
                family.name,
                0.0,
            )
        )

        if cooldown > now:
            item.score = -1_000_000.0
            continue

        # Weakness creates priority, but repeated failures reduce priority so
        # the system explores another family instead of hammering one problem.
        item.score = (
            family.priority * 10.0
            + target_gap * 8.0
            + evidence_gap * 0.8
            + min(
                24.0,
                recency_hours,
            )
            - failure_rate * 18.0
            - item.recent_failures * 4.0
            + math.log1p(
                item.chunks_learned
            )
        )

    return sorted(
        stats.values(),
        key=lambda item: (
            -item.score,
            item.successes,
            item.family,
        ),
    )


def _request_digest(
    request: str,
) -> str:
    return hashlib.sha256(
        _normalise_request(
            request
        ).encode("utf-8")
    ).hexdigest()


def generate_request(
    family_name: str,
    state: CurriculumState,
) -> str:
    family = FAMILY_BY_NAME[
        family_name
    ]

    cursor = int(
        state.family_cursor.get(
            family_name,
            0,
        )
    )

    recent = {
        _normalise_request(
            request
        )
        for request in state.recent_requests
    }

    combinations = []

    for pattern_index, pattern in enumerate(
        family.request_patterns
    ):
        for concept_index, concept in enumerate(
            family.concepts
        ):
            combinations.append(
                (
                    pattern_index,
                    concept_index,
                    pattern.format(
                        concept=concept
                    ),
                )
            )

    # Deterministic rotation with a state seed gives reproducibility while
    # still spreading attempts across combinations.
    rng = random.Random(
        state.seed
        + state.iteration * 1_000_003
        + sum(
            ord(character)
            for character in family_name
        )
    )

    rng.shuffle(
        combinations
    )

    if combinations:
        shift = cursor % len(
            combinations
        )

        combinations = (
            combinations[shift:]
            + combinations[:shift]
        )

    selected = None

    for _pattern, _concept, request in combinations:
        if (
            _normalise_request(request)
            not in recent
        ):
            selected = request
            break

    if selected is None:
        base = combinations[
            cursor % len(combinations)
        ][2]

        # A deterministic variation changes data size and presentation
        # constraints without altering the capability family.
        variations = (
            " Include keyboard accessibility and responsive mobile layout.",
            " Include sample data, reset behavior and clear validation feedback.",
            " Keep it offline-capable and self-contained.",
            " Include an accessible help panel and deterministic test data.",
        )

        selected = (
            base
            + variations[
                state.iteration
                % len(variations)
            ]
        )

    if family.product_kind == "browser":
        if (
            "self-contained" not in selected.lower()
            and "self contained" not in selected.lower()
        ):
            selected += (
                " Produce one self-contained index.html."
            )

    state.family_cursor[
        family_name
    ] = cursor + 1

    state.recent_requests.append(
        selected
    )

    state.recent_requests = (
        state.recent_requests[
            -RECENT_REQUEST_LIMIT:
        ]
    )

    return selected


def choose_next_request(
    state: CurriculumState,
) -> tuple[CurriculumFamily, str, list[FamilyStats]]:
    ranked = score_families(
        state
    )

    available = [
        item
        for item in ranked
        if item.score > -100_000
    ]

    if not available:
        state.cooldown_until.clear()
        available = score_families(
            state
        )

    if not available:
        raise RuntimeError(
            "No curriculum families are available."
        )

    # Choose among the strongest three to avoid starving near-equal families.
    top = available[:3]

    rng = random.Random(
        state.seed
        + state.iteration * 97
    )

    weights = [
        max(
            0.1,
            item.score
            - min(
                candidate.score
                for candidate in top
            )
            + 1.0,
        )
        for item in top
    ]

    chosen_stats = rng.choices(
        top,
        weights=weights,
        k=1,
    )[0]

    family = FAMILY_BY_NAME[
        chosen_stats.family
    ]

    request = generate_request(
        family.name,
        state,
    )

    return family, request, ranked


def record_outcome(
    state: CurriculumState,
    *,
    family: CurriculumFamily,
    request: str,
    success: bool,
    chunks_learned: int,
    elapsed_seconds: float,
    workspace: str,
    report: str,
) -> dict[str, Any]:
    now = time.time()

    state.iteration += 1

    if success:
        state.family_successes[
            family.name
        ] = (
            int(
                state.family_successes.get(
                    family.name,
                    0,
                )
            )
            + 1
        )

        state.failure_streaks[
            family.name
        ] = 0

        state.cooldown_until.pop(
            family.name,
            None,
        )

    else:
        state.family_failures[
            family.name
        ] = (
            int(
                state.family_failures.get(
                    family.name,
                    0,
                )
            )
            + 1
        )

        streak = (
            int(
                state.failure_streaks.get(
                    family.name,
                    0,
                )
            )
            + 1
        )

        state.failure_streaks[
            family.name
        ] = streak

        if streak >= MAX_FAILURE_STREAK:
            # Increasing cooldown stops a broken route from consuming every
            # curriculum iteration.
            cooldown_minutes = min(
                12 * 60,
                15 * (2 ** min(5, streak - MAX_FAILURE_STREAK)),
            )

            state.cooldown_until[
                family.name
            ] = (
                now
                + cooldown_minutes * 60
            )

    save_state(
        state
    )

    record = {
        "timestamp":
            now,

        "iteration":
            state.iteration,

        "family":
            family.name,

        "capabilities":
            list(
                family.capabilities
            ),

        "request":
            request,

        "request_sha256":
            _request_digest(
                request
            ),

        "success":
            bool(success),

        "chunks_learned":
            int(chunks_learned),

        "elapsed_seconds":
            round(
                float(elapsed_seconds),
                3,
            ),

        "workspace":
            workspace,

        "report_excerpt":
            str(report or "")[
                :2_000
            ],

        "failure_streak":
            int(
                state.failure_streaks.get(
                    family.name,
                    0,
                )
            ),

        "cooldown_until":
            float(
                state.cooldown_until.get(
                    family.name,
                    0.0,
                )
            ),
    }

    _append_jsonl(
        EVENT_FILE,
        record,
    )

    _append_jsonl(
        REQUEST_FILE,
        {
            "timestamp":
                now,

            "iteration":
                state.iteration,

            "family":
                family.name,

            "request":
                request,

            "success":
                bool(success),
        },
    )

    return record


def coverage_report() -> dict[str, Any]:
    state = load_state()
    ranked = score_families(
        state
    )

    return {
        "iteration":
            state.iteration,

        "families": [
            {
                "family":
                    item.family,

                "score":
                    round(
                        item.score,
                        2,
                    ),

                "successes":
                    item.successes,

                "failures":
                    item.failures,

                "recent_failures":
                    item.recent_failures,

                "chunks_learned":
                    item.chunks_learned,

                "memory_evidence":
                    item.memory_evidence,

                "cooldown_until":
                    state.cooldown_until.get(
                        item.family,
                        0.0,
                    ),
            }
            for item in ranked
        ],
    }


